import assert from 'node:assert/strict';
import {buildMapContent} from '../modules/map-content.js';
import {growthRoadmap} from '../growth-roadmap.js';
import {connected} from '../modules/hex-map.js';
const expected=growthRoadmap.flatMap(c=>c.cards.flatMap(g=>g.tasks)).map(t=>t.id).sort();
const nodes=buildMapContent({getItem:()=>null});
assert.equal(nodes.length,13);
assert.deepEqual(nodes.flatMap(n=>n.tasks.map(t=>t.id)).sort(),expected);
assert.equal(nodes.filter(n=>n.state==='done').length,2);
assert.equal(nodes.find(n=>n.id==='award-wins').tasks.reduce((s,t)=>s+t.awardCount,0),8);
assert(connected([{id:'me',q:0,r:0},...nodes]));
for(const n of nodes)assert.equal(n.state==='done',n.tasks.every(t=>t.status==='done'));
const local=buildMapContent({getItem:()=>JSON.stringify([{id:'local-case',cardId:'case-studies',title:'Case note'},{id:'local-team',cardId:'team',title:'Team note'}])});
assert.equal(local.flatMap(n=>n.tasks).length,expected.length+2);
assert(local.find(n=>n.id==='workbench').tasks.some(t=>t.id==='local-case'));
assert(local.find(n=>n.id==='team-building').tasks.some(t=>t.id==='local-team'));
assert.equal(buildMapContent({getItem:()=>'{bad json'}).length,13);
console.log('PASS MAP source coverage, connectivity, exact achievement counts, pending/completed derivation and local task inclusion');
